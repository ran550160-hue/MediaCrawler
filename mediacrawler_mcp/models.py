@dataclass(slots=True)
class ClaimDraft:
    """A future human-authored claim proposal; never generated by analysis code."""

    claim_id: str
    research_run_id: str
    text: str
    evidence_ids: list[str]
    claim_type: str
    schema_version: str = "claim-draft-v1"

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)
